<?php
/**
 * Writes and removes the drop-in files for pages WordPress shows when it
 * cannot run normally.
 *
 * Files carry a signature line. The plugin never overwrites or deletes a
 * drop-in without it, so drop-ins from other plugins or hosts stay intact.
 *
 * @package Adminora
 */

namespace Adminora;

use Adminora\Modules\Error_Pages\Error_Pages;

defined( 'ABSPATH' ) || exit;

/**
 * Drop-in manager.
 */
class Dropins {

	const SIGNATURE = 'Adminora drop-in';

	/**
	 * Drop-in file => [ setting key, page key, HTTP status, Retry-After seconds ].
	 *
	 * @return array
	 */
	public static function files() {
		return array(
			'php-error.php'   => array( 'error_pages.critical', 'critical', 500, 0 ),
			'db-error.php'    => array( 'error_pages.db', 'db', 500, 300 ),
			'maintenance.php' => array( 'error_pages.maintenance', 'maintenance', 503, 60 ),
		);
	}

	/**
	 * Absolute path of a drop-in.
	 *
	 * @param string $file File name.
	 * @return string
	 */
	public static function path( $file ) {
		return trailingslashit( WP_CONTENT_DIR ) . $file;
	}

	/**
	 * Whether an existing file was written by this plugin.
	 *
	 * @param string $file File name.
	 * @return bool
	 */
	public static function is_ours( $file ) {
		$path = self::path( $file );

		if ( ! is_readable( $path ) ) {
			return false;
		}

		// Only the header is needed to spot the signature.
		$head = file_get_contents( $path, false, null, 0, 512 ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- Local file.

		return false !== $head && false !== strpos( $head, self::SIGNATURE );
	}

	/**
	 * Whether a drop-in should exist under the current settings.
	 *
	 * @param string $file File name.
	 * @return bool
	 */
	public static function wanted( $file ) {
		$files = self::files();

		return Settings::module_on( 'error_pages' ) && Settings::get( $files[ $file ][0] );
	}

	/**
	 * Writes wanted drop-ins and removes unwanted ones.
	 *
	 * @return void
	 */
	public static function sync() {
		foreach ( array_keys( self::files() ) as $file ) {
			$path = self::path( $file );

			if ( file_exists( $path ) && ! self::is_ours( $file ) ) {
				continue;
			}

			if ( self::wanted( $file ) ) {
				Files::put( $path, self::build( $file ) );
			} elseif ( file_exists( $path ) ) {
				Files::delete( $path );
			}
		}
	}

	/**
	 * Removes every drop-in this plugin wrote.
	 *
	 * @return void
	 */
	public static function remove_all() {
		foreach ( array_keys( self::files() ) as $file ) {
			if ( self::is_ours( $file ) ) {
				Files::delete( self::path( $file ) );
			}
		}
	}

	/**
	 * Status of each drop-in for the settings page.
	 *
	 * @return array File name => one of active, conflict, off, unwritable, missing.
	 */
	public static function status() {
		$status = array();

		foreach ( array_keys( self::files() ) as $file ) {
			$exists = file_exists( self::path( $file ) );

			if ( $exists && ! self::is_ours( $file ) ) {
				$status[ $file ] = 'conflict';
			} elseif ( ! self::wanted( $file ) ) {
				$status[ $file ] = 'off';
			} elseif ( $exists ) {
				$status[ $file ] = 'active';
			} elseif ( ! Files::writable( WP_CONTENT_DIR ) ) {
				$status[ $file ] = 'unwritable';
			} else {
				$status[ $file ] = 'missing';
			}
		}

		return $status;
	}

	/**
	 * Builds the PHP source of a drop-in with a static HTML snapshot.
	 *
	 * @param string $file File name.
	 * @return string
	 */
	private static function build( $file ) {
		list( , $page, $status, $retry ) = self::files()[ $file ];

		$html = Error_Pages::render( $page, array(), true );

		$json_guard = '';

		if ( 'php-error.php' === $file ) {
			$json_guard = "if ( ( defined( 'REST_REQUEST' ) && REST_REQUEST ) || ( defined( 'DOING_AJAX' ) && DOING_AJAX ) || ( function_exists( 'wp_is_json_request' ) && wp_is_json_request() ) ) {\n"
				. "\tif ( ! headers_sent() ) {\n"
				. "\t\thttp_response_code( 500 );\n"
				. "\t\theader( 'Content-Type: application/json; charset=utf-8' );\n"
				. "\t}\n"
				. "\techo '{\"code\":\"internal_server_error\",\"message\":\"There has been a critical error on this website.\",\"data\":{\"status\":500}}';\n"
				. "\treturn;\n"
				. "}\n\n";
		}

		$retry_header = $retry ? "\theader( 'Retry-After: " . (int) $retry . "' );\n" : '';

		return "<?php\n"
			. "/**\n"
			. ' * ' . self::SIGNATURE . ': ' . $file . "\n"
			. " *\n"
			. " * Generated by the Adminora plugin. Changes here are overwritten when\n"
			. " * its settings are saved. Turn the page off in Appearance > Customize >\n"
			. " * Adminora to remove this file.\n"
			. " */\n\n"
			. "defined( 'ABSPATH' ) || exit;\n\n"
			. $json_guard
			. "if ( ! headers_sent() ) {\n"
			. "\thttp_response_code( " . (int) $status . " );\n"
			. "\theader( 'Content-Type: text/html; charset=utf-8' );\n"
			. "\theader( 'Cache-Control: no-cache, must-revalidate, max-age=0' );\n"
			. $retry_header
			. "}\n\n"
			// var_export() writes the page as a single-quoted PHP string literal.
			. '$adminora_page = ' . var_export( $html, true ) . ";\n" // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export -- Builds PHP source for the drop-in file, not debug output.
			. self::note_code( $html )
			. 'echo $adminora_page;' . "\n";
	}

	/**
	 * Drop-in code that shows the administrators' note only to signed-in
	 * administrators, and removes it for everyone else.
	 *
	 * @param string $html Page HTML.
	 * @return string
	 */
	private static function note_code( $html ) {
		if ( false === strpos( $html, Error_Pages::NOTE_MARKER ) ) {
			return '';
		}

		$slot = '<p class="adminora-page__note">' . Error_Pages::NOTE_MARKER . '</p>';
		$note = esc_html( Error_Pages::admin_note_text() );

		// phpcs:disable WordPress.PHP.DevelopmentFunctions.error_log_var_export -- Builds PHP source for the drop-in file, not debug output.
		return "if ( function_exists( 'is_user_logged_in' ) && function_exists( 'current_user_can' ) && is_user_logged_in() && current_user_can( 'manage_options' ) ) {\n"
			. "\t" . '$adminora_page = str_replace( ' . var_export( Error_Pages::NOTE_MARKER, true ) . ', ' . var_export( $note, true ) . ', $adminora_page );' . "\n"
			. "} else {\n"
			. "\t" . '$adminora_page = str_replace( ' . var_export( $slot, true ) . ", '', " . '$adminora_page );' . "\n"
			. "}\n";
		// phpcs:enable
	}
}
