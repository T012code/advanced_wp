	/**
	 * Default icon for a core or common menu slug.
	 *
	 * @param string $slug Menu slug.
	 * @return string Icon name, or '' to keep the item's own icon.
	 */
	public static function default_for( $slug ) {
		$map = array(
			'index.php'                         => 'dashboard',
			'edit.php'                          => 'pen',
			'upload.php'                        => 'image',
			'edit.php?post_type=page'           => 'file',
			'edit-comments.php'                 => 'message',
			'themes.php'                        => 'palette',
			'plugins.php'                       => 'plug',
			'users.php'                         => 'users',
			'profile.php'                       => 'user',
			'tools.php'                         => 'wrench',
			'options-general.php'               => 'sliders',
			'woocommerce'                       => 'bag',
			'edit.php?post_type=product'        => 'package',
			'wc-admin&path=/analytics/overview' => 'chart',
			'woocommerce-marketing'             => 'chart',
		);

		if ( isset( $map[ $slug ] ) ) {
			return $map[ $slug ];
		}

		return 0 === strpos( $slug, 'edit.php?post_type=' ) ? 'file-text' : '';
	}
