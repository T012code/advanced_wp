	/**
	 * Full SVG markup for an icon.
	 *
	 * @param string $name Icon name.
	 * @param int    $size Size in pixels.
	 * @return string
	 */
	public static function svg( $name, $size = 18 ) {
		$all  = self::all();
		$body = isset( $all[ $name ] ) ? $all[ $name ] : $all['circle'];

		return '<svg xmlns="http://www.w3.org/2000/svg" width="' . (int) $size . '" height="' . (int) $size . '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' . $body . '</svg>';
	}

